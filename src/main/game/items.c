/* Empties the battle gauges (BATTLE_SETUP.gauges, up to 1000 in a battle) */
void clearBattleGauges(void) {
    s32 i;

    for (i = 7; i >= 0; i--) {
        BATTLE_SETUP.gauges[i] = 0;
    }
}

/* The ITEMS entry of item `id` (from 1), or NULL */
ItemInfo *getItem(s32 id) {
    if (id <= 0) {
        return NULL;
    }
    return &ITEMS[id - 1];
}

/* The category of an item's type (ITEM_TYPE_CATEGORIES) */
u8 getItemCategory(s32 id) {
    return ITEM_TYPE_CATEGORIES[getItem(id)->type];
}

/* ITEM_FUNCS->isKind */
s32 isItemKind(s32 item, s32 kind) {
    return getItem(item)->unk8 == kind;
}

/*
 * Copies the items of ITEM_LISTS[type] the player has (with the top bit, equipped ones too);
 * returns how many
 */
s32 listItems(s32 type, u16 *out) {
    s32 index;
    s32 all;
    u16 *p;
    s32 n;

    all = (type >> 31) != 0;
    index = type & 0x7FFFFFFF;

    if (index >= 5) {
        return 0;
    }
    n = 0;
    for (p = ITEM_LISTS[index]; *p != 0; p++) {
        if (GAME.items[*p] != 0 || (all && GAME.equippedItems[*p] != 0)) {
            *out++ = *p;
            n++;
        }
    }
    return n;
}

