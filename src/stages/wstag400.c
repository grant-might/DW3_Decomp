/* Creates the event object when flag 0x1A26 is set and 0x1C4B is not */
void updateStage(StageTask *task, void **children) {
    switch (task->state) {
    case TASK_INIT:
    default:
        if (FLAGS_00.checkCondition(0x1A26, 1) && FLAGS_00.checkCondition(0x1C4B, 0)) {
            children[0] = FIELDSTG_startEvent(0x514);
        }
        task->nextState(task);
        break;
    case TASK_RUN:
    case TASK_DONE:
    case TASK_KILL:
        break;
    }
}

