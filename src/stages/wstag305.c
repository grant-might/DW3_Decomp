s32 stepAnimationOnce(StageTileAnim *obj, AnimFrame *frames, s32 depth) {
    AnimFrame *frame = &frames[obj->anim.index];
    s32 dt = GFX.funcs.getFrameTime();

    if (dt > 4) {
        dt = 4;
    }
    if (depth == 0) {
        obj->anim.timer -= dt;
    }
    if (obj->anim.timer <= 0) {
        frame++;
        obj->anim.index++;
        obj->anim.timer += frame->duration;
        if (frame->frame == 0xFF) {
            return 0xFF;
        }
        stepAnimationOnce(obj, frames, depth + 1);
    }
    return frame->frame;
}

void func_800A4D7C(StageSoundTile *task) {
    StageTile *rec;
    StageTile *tile;
    s32 frame;

    switch (task->state) {
    case TASK_INIT:
    default:
        for (rec = D_800990B4.objects; rec->unk2 != 0; rec++) {
            if (rec->anim == 1) {
                task->obj.anim.index = 0;
                task->obj.anim.timer = D_800A6EB8[0].duration;
                task->obj.tile = rec;
            }
        }
        task->nextState(task);
        break;
    case TASK_RUN:
        tile = task->obj.tile;
        switch (task->substate) {
        case 0:
        default:
            tile->frame = 5;
            tile->visible = 1;
            break;
        case 1:
            tile->visible = 1;
            frame = stepAnimationOnce(&task->obj, D_800A6EB8, 0);
            if (frame != 0xFF) {
                tile->frame = frame;
            } else {
                tile->frame = 10;
                task->nextSubstate(task);
                SOUND.keyOff(0xA0042FCB, task->voice);
            }
            break;
        case 2:
            tile->visible = 1;
            tile->frame = 10;
            break;
        }
        break;
    case TASK_DONE:
    case TASK_KILL:
        break;
    }
}

