void updateStage(StageTask *task, void **children) {
    switch (task->state) {
    case TASK_INIT:
    default:
        task->nextState(task);
        if (FLAGS_00.checkCondition(0x402B, 1) && FLAGS_00.checkCondition(0x402C, 0)) {
            children[0] = FIELDSTG_startEvent(0x4FA);
        }
        break;
    case TASK_RUN:
    case TASK_DONE:
    case TASK_KILL:
        break;
    }
}

