void STDGNAME_updateScene(Task *task, void **children) {
    RECT rect;
    Layer *layer;

    switch (task->state) {
    case TASK_INIT:
    default:
        GFX.funcs.reset();
        GFX.funcs.allocPrimBuffers(0x5000);
        GFX.funcs.setDisplayMode(320, 240, 0, 0);
        rect.x = 0;
        rect.y = 0;
        rect.w = 320;
        rect.h = 240;
        layer = GFX.funcs.createLayer(&rect, 3, 0x1000);
        layer->setBgColor(layer, 0, 0, 0);
        *children = STDGNAME_createScreen();
        task->nextState(task);
        break;
    case TASK_RUN:
    case TASK_DONE:
    case TASK_KILL:
        break;
    }
}

Task *STDGNAME_start(void) {
    return createTask(STDGNAME_updateScene, sizeof(Task), sizeof(void *));
}

void STDGNAME_startFader(FadeTask *task, s32 fadeIn, s32 duration) {
    task->setState(task, TASK_RUN);
    task->substate = 1;
    task->fadeIn = fadeIn;
    if (fadeIn == 0) {
        task->level = 0;
        task->delta = 0xFF00 / duration;
    } else {
        task->level = 0xFF00;
        task->delta = -(0xFF00 / duration);
    }
}

void STDGNAME_drawFader(FadeTask *task) {
    Layer *layer = GFX.funcs.getLayer(task->layer);
    u_long *ot = (u_long *)layer->getOtEntry(layer, task->depth);
    POLY_F4 *poly = GFX.funcs.getPrim();
    DR_TPAGE *mode;

    setlen(poly, 5);
    poly->code = 0x2A;
    poly->r0 = poly->g0 = poly->b0 = task->level >> 8;
    poly->x0 = poly->x2 = 0;
    poly->x1 = poly->x3 = 320;
    poly->y0 = poly->y1 = 0;
    poly->y2 = poly->y3 = 256;
    addPrim(ot, poly);
    mode = (DR_TPAGE *)(poly + 1);
    setlen(mode, 1);
    mode->code[0] = 0xE1000245;
    addPrim(ot, mode);
    GFX.funcs.setPrim(mode + 1);
}

void STDGNAME_updateFader(FadeTask *task) {
    switch (task->state) {
    case TASK_INIT:
    default:
        task->nextState(task);
        break;
    case TASK_RUN:
        if (task->substate != 0) {
            task->level += task->delta;
            if (task->fadeIn == 0) {
                if (task->level > 0xFF00) {
                    task->level = 0xFF00;
                    task->state = TASK_DONE;
                }
            } else if (task->level < 0) {
                task->level = 0;
                task->state = TASK_DONE;
            }
            STDGNAME_drawFader(task);
        }
        break;
    case TASK_DONE:
        STDGNAME_drawFader(task);
        break;
    case TASK_KILL:
        break;
    }
}

FadeTask *STDGNAME_createFader(void) {
    FadeTask *task = createTask(STDGNAME_updateFader, sizeof(FadeTask), 0);

    task->start = STDGNAME_startFader;
    task->layer = 0x1000;
    task->depth = 6;
    return task;
}

void STDGNAME_startTween(Tween *tween, s32 open) {
    tween->active = 1;
    if (open) {
        SOUND.playSound(SOUND_MENU_OPEN);
        tween->step = 0x1000 / tween->duration;
        tween->value = 0;
    } else {
        SOUND.playSound(SOUND_MENU_CLOSE);
        tween->value = 0x1000;
        tween->step = -(0x1000 / tween->duration * 2);
    }
}

s32 STDGNAME_updateTween(Tween *tween) {
    if (tween->active == 0) {
        return 1;
    }
    tween->value += tween->step;
    if (tween->step > 0) {
        if (tween->value > 0x1000) {
            tween->value = 0x1000;
            tween->active = 0;
            return 1;
        }
    } else if (tween->value < 0) {
        tween->value = 0;
        tween->active = 0;
        return 1;
    }
    return 0;
}
